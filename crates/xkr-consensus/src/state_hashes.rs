/// Testnet state hashes (none: testnet chains are rebuilt).
pub const TESTNET_STATE_HASHES: &[(u32, &str)] = &[];

/// The built-in state hashes of `network`.
#[must_use]
pub const fn for_network(network: Network) -> &'static [(u32, &'static str)] {
    match network {
        Network::Mainnet => MAINNET_STATE_HASHES,
        Network::Testnet => TESTNET_STATE_HASHES,
    }
}

/// The built-in state hash of `span` on `network`, if the list has it.
#[must_use]
pub fn builtin(network: Network, span: u32) -> Option<&'static str> {
    let list = for_network(network);
    list.get(span as usize)
        .filter(|(s, _)| *s == span)
        .or_else(|| list.iter().find(|(s, _)| *s == span))
        .map(|(_, h)| *h)
}

